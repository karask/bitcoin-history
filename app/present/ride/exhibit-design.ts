export const exhibitDesigns: Readonly<Record<string, Readonly<ExhibitDesign>>> = designs;
export function exhibitDesign(event: Pick<PresentationEvent, "slug">): Readonly<ExhibitDesign> {
  // A safe archival display for future records; coverage tests require an explicit
  // editorial assignment for every record currently in the corpus.
  return designs[event.slug] ?? { kind: "archive", motif: "record", state: "documented" };
}
export function exhibitKind(event: Pick<PresentationEvent, "slug">): ExhibitKind {
  return exhibitDesign(event).kind;
}
