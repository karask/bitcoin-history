// Editorial assignments, not category/keyword guesses. Related events can share
// architecture, but their actual mechanism and historical stage must stay distinct.
// These are symbolic dioramas, NOT reconstructions of premises or official seals.
const designs: Record<string, ExhibitDesign> = {};
function assign(kind: ExhibitKind, motif: string, state: string, slugs: string) {
  for (const slug of slugs.split(/\s+/).filter(Boolean)) {
    if (designs[slug]) throw new Error(`Duplicate exhibit design: ${slug}`);
    designs[slug] = { kind, motif, state };
  }
}

